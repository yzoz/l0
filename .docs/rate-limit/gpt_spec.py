# ============================================================
# STATE MODEL
# ============================================================

@dataclass(slots=True)
class RateLimitState:
    """
    Состояние алгоритма.

    next_slot:
        Временная отметка следующего штатного слота.

    in_flight:
        Количество операций записи, которые были допущены,
        но ещё не завершились.

    queue:
        FIFO-очередь ожидающих транзакций.

    active_attempts:
        Набор идентификаторов активных попыток записи.
        Нужен для защиты от двойного завершения одной попытки.

    Все изменения состояния должны быть согласованы между
    конкурирующими задачами. Конкретный механизм синхронизации
    определяется реализацией.
    """
    next_slot: float | None = None
    in_flight: int = 0


# ============================================================
# ADMISSION POLICY
# ============================================================

class AdmissionPolicy(Protocol):
    """
    Контракт алгоритма допуска транзакций.

    Алгоритм должен:
      1. Принимать транзакции в FIFO-порядке.
      2. Ограничивать штатную скорость значением TPS.
      3. Ограничивать параллельность значением max_in_flight.
      4. Допускать первую транзакцию после простоя немедленно.
      5. Не накапливать пропущенные слоты для последующего всплеска.
      6. При ошибке записи освобождать ёмкость и немедленно
         передавать возможность следующей ожидающей транзакции.
      7. Не допускать двойного завершения попыток.

    ВАЖНО:
        Немедленный допуск после ошибки является исключением
        из штатного расписания. Поэтому TPS не является строгой
        верхней границей в любой скользящий интервал времени.
    """

    async def submit(self, transaction: Transaction) -> None:
        """
        Зарегистрировать транзакцию для обработки.

        Контракт:
          - регистрация сохраняет FIFO-порядок;
          - транзакция не считается записанной только потому,
            что она зарегистрирована;
          - фактический допуск определяется алгоритмом;
          - повторная регистрация одного transaction_id должна
            обрабатываться согласно отдельному контракту
            дедупликации вызывающей системы.
        """
        ...

    async def on_write_success(self, attempt_id: str) -> None:
        """
        Зафиксировать успешное завершение операции записи.

        Контракт:
          - attempt_id должен соответствовать активной попытке;
          - активная ёмкость освобождается ровно один раз;
          - успешное завершение само по себе не даёт права
            на досрочный допуск следующей транзакции;
          - следующая транзакция допускается только при наличии
            штатного временного слота и свободной ёмкости.
        """
        ...

    async def on_write_failure(self, attempt_id: str) -> None:
        """
        Зафиксировать ошибку операции записи.

        Контракт:
          - активная ёмкость освобождается ровно один раз;
          - если очередь не пуста, следующая транзакция получает
            освобождённую возможность немедленно;
          - FIFO-порядок сохраняется;
          - не допускается повторная выдача одной возможности;
          - если очередь пуста, возможность не накапливается;
          - после исключительного допуска штатное расписание
            должно продолжиться без компенсационного всплеска.
        """
        ...


# ============================================================
# SCHEDULING RULES
# ============================================================

def scheduling_contract(
    config: RateLimitConfig,
    state: RateLimitState,
) -> None:
    """
    СПЕЦИФИКАЦИЯ РАСПИСАНИЯ — НЕ РЕАЛИЗАЦИЯ.

    Обозначения:
        R = config.tps
        T = 1 / R
        now = монотонное текущее время

    Правила:

    1. Если очередь пуста:
         - не выдавать допуски;
         - не накапливать разрешения;
         - при следующем поступлении транзакции начать
           с немедленного допуска, если ёмкость доступна.

    2. При первом допуске после простоя:
         - разрешить немедленный старт;
         - назначить следующий штатный слот через T.

    3. При обычном штатном допуске:
         - следующая транзакция может стартовать только
           на соответствующем временном слоте;
         - после допуска обновить next_slot;
         - не создавать дополнительные слоты из-за
           медленного завершения предыдущей записи.

    4. Если штатный слот наступил, но in_flight достиг
       max_in_flight:
         - не начинать запись;
         - ожидать освобождения ёмкости;
         - не запускать несколько записей в один слот
           только потому, что ожидание затянулось.

    5. После долгой паузы:
         - не воспроизводить пропущенные слоты;
         - не допускать транзакции пачкой;
         - возобновить штатный темп.

    6. При ошибке записи:
         - освободить одну единицу in_flight;
         - при непустой очереди немедленно допустить
           следующую транзакцию;
         - такое исключение может временно нарушить
           равномерность штатного расписания.

    7. При успехе записи:
         - освободить одну единицу in_flight;
         - не выдавать дополнительный внеплановый допуск.

    Временная арифметика должна учитывать задержки планировщика.
    Реализация обязана явно определить, как пересчитывается
    next_slot после задержки и после исключительного допуска,
    чтобы старые слоты не создавали всплеск.
    """
    raise NotImplementedError(
        "Документирующий контракт. Реализовать отдельным алгоритмом."
    )


